function offsetKarachiDate(daysFromToday: number): string {
  const now = new Date();
  // Format today's date in Asia/Karachi first
  const karachiStr = new Intl.DateTimeFormat('en-CA', {
    timeZone: 'Asia/Karachi',
    year: 'numeric',
    month: '2-digit',
    day: '2-digit',
  }).format(now);
  const [y, m, d] = karachiStr.split('-').map(Number);
  const baseUtc = Date.UTC(y, m - 1, d);
  const target = new Date(baseUtc + daysFromToday * 86_400_000);
  return target.toISOString().slice(0, 10);
}

function offsetIsoTimestamp(daysAgo: number, hourOffset = 10): string {
  const date = new Date(Date.now() - daysAgo * 86_400_000);
  date.setHours(hourOffset, 15, 0, 0);
  return date.toISOString();
}

